"""SG-06.1, SG-06.3, SG-06.4 Model card, frozen test predictions, and demo encounters.

Run:    python -m ml.model_card   (after ml.train for all three runs and ml.inference)
Writes: ml/reports/model_card.md            selection rationale, frozen model, test summary, demo IDs
        ml/artifacts/demo_histories.csv      message histories of the demo encounters (gitignored)

Demo encounters come from the validation partition (never used to fit the model) plus
one train encounter with no early message (never used for fitting either).
"""

import json

import pandas as pd

from ml.config import ARTIFACTS_DIR, REPORTS_DIR
from ml.data import load_labels, load_messages
from ml.inference import DEFAULT_MODEL_DIR, load_model

RUNS = {"persistence": "Persistence (SG-05.1)", "upgrade_base": "Upgrade, base (SG-05.2)", "upgrade_base_mre": "Upgrade, base_mre (SG-05.3)"}
SHIPPED = "upgrade_base"


def _selection_table() -> pd.DataFrame:
    rows = []
    for run, name in RUNS.items():
        path = REPORTS_DIR / f"{run}.json"
        if not path.exists():
            raise FileNotFoundError(f"{path} not found; run python -m ml.train for {run}")
        m = json.loads(path.read_text())["validation"]["primary_cohort"]
        c = m["per_tier"]["Critical"]
        lo, hi = m["critical_recall_95ci"]
        rows.append(
            {
                "model": name + (" **shipped**" if run == SHIPPED else ""),
                "Critical recall (95% CI)": f"{c['recall']:.3f} ({lo:.3f}–{hi:.3f})",
                "Critical precision": f"{c['precision']:.3f}",
                "Elevated recall": f"{m['per_tier']['Elevated']['recall']:.3f}",
                "Safe recall": f"{m['per_tier']['Safe']['recall']:.3f}",
                "false Critical": m["false_critical_alarms"],
                "Critical → Safe": m["critical_predicted_safe"],
            }
        )
    return pd.DataFrame(rows).set_index("model")


def _demo_encounters(labels: pd.DataFrame) -> pd.DataFrame:
    v = pd.read_csv(DEFAULT_MODEL_DIR / "validation_predictions.csv").set_index("encounter_id")
    v = v[~v["final_is_early"]]
    crit = v["final_tier"] == "Critical"
    picks = [
        ("Upgrade caught a Critical the rule missed", v[v["upgraded"] & crit].sort_values("p_critical", ascending=False)),
        ("Upgrade false alarm", v[v["upgraded"] & ~crit].sort_values("p_critical", ascending=False)),
        ("Rule and model both correct: Critical", v[(v["persistence_tier"] == "Critical") & crit]),
        ("Missed: looked Safe 2 days out (limitation)", v[(v["predicted_tier"] == "Safe") & crit].loc[lambda d: d.index == "train:8732"]
         if "train:8732" in v.index else v[(v["predicted_tier"] == "Safe") & crit]),
        ("Correct Safe", v[(v["predicted_tier"] == "Safe") & (v["final_tier"] == "Safe")]),
    ]
    rows = [
        {"encounter_id": d.index[0], "case": case, "persistence_tier": d.iloc[0]["persistence_tier"],
         "predicted_tier": d.iloc[0]["predicted_tier"], "final_tier": d.iloc[0]["final_tier"]}
        for case, d in picks if len(d)
    ]
    unusable = labels[~labels["usable"]].sort_index().index[0]
    rows.append({"encounter_id": unusable, "case": "Unable to assess: no message ≥ 2 days out",
                 "persistence_tier": "—", "predicted_tier": "unable_to_assess", "final_tier": labels.loc[unusable, "final_tier"]})
    return pd.DataFrame(rows).set_index("encounter_id")


def main() -> None:
    model = load_model()
    labels = load_labels()
    test_path = ARTIFACTS_DIR / "predictions_test.csv"
    if not test_path.exists():
        raise FileNotFoundError(f"{test_path} not found; run python -m ml.inference --source test")
    test = pd.read_csv(test_path)
    demo = _demo_encounters(labels)

    messages = load_messages("train")
    histories = messages[messages["encounter_id"].isin(demo.index)].sort_values(["encounter_id", "time_to_tca"], ascending=[True, False])
    histories.to_csv(ARTIFACTS_DIR / "demo_histories.csv", index=False)

    test_tiers = test["predicted_tier"].value_counts().reindex(["Critical", "Elevated", "Safe"]).fillna(0).astype(int)
    lines = [
        "# Model card",
        "",
        "Generated by `python -m ml.model_card`. Decisions are in [docs/ML_DECISIONS.md](../../docs/ML_DECISIONS.md).",
        "",
        "## What it does",
        "",
        "Predicts each encounter's final tier (Safe / Elevated / Critical) from messages sent at least 2 days "
        "before closest approach. The organisers' tier rules are applied to the latest early message "
        "(persistence); a gradient-boosted classifier can then upgrade the tier to Critical when its score "
        "passes a threshold fixed on training folds. It never lowers a tier.",
        "",
        "## Model selection (SG-06.1)",
        "",
        "Validation partition, primary cohort (1,786 encounters, 126 Critical). Accuracy is not used for selection.",
        "",
        _selection_table().to_markdown(),
        "",
        "**Selected: upgrade, base.** It has the highest Critical recall. The cost is 21 more false Critical "
        "alarms than persistence, within the D7 budget of at most 3 false alarms per extra catch. "
        "`base_mre` adds `max_risk_estimate` but catches fewer Critical encounters, so the shipped model "
        "does not depend on it (D8). Confidence intervals overlap: the gain is real but modest. "
        "Upgrades also move some true Elevated encounters to Critical, so Elevated recall drops (0.82 → 0.77).",
        "",
        "## Frozen model (SG-06.3)",
        "",
        "| Field | Value |",
        "| --- | --- |",
        f"| Version | `{model['model_version']}` |",
        f"| Bundle SHA-256 | `{model['model_sha256']}` |",
        f"| Training data SHA-256 | `{model['train_sha256']}` |",
        f"| Upgrade threshold | {model['threshold']} |",
        f"| Features | {len(model['feature_columns'])} (`base` set in `ml/features.py`) |",
        f"| scikit-learn | {model['sklearn_version']} |",
        "",
        "Settings were frozen before scoring the test file. `test_data.csv` has no outcomes, so it is scored "
        "for demo predictions only and has no test metrics. All reported metrics are validation metrics.",
        "",
        f"Test predictions ({len(test):,} encounters, `ml/artifacts/predictions_test.csv`): "
        f"Critical {test_tiers['Critical']:,} (of which {int(test['upgraded'].sum())} upgraded), "
        f"Elevated {test_tiers['Elevated']:,}, Safe {test_tiers['Safe']:,}, "
        f"unable to assess {(test['status'] == 'unable_to_assess').sum():,}.",
        "",
        "## Demo encounters (SG-06.4)",
        "",
        "Selected illustrations from data the model never trained on. Histories: `ml/artifacts/demo_histories.csv`.",
        "",
        demo.to_markdown(),
        "",
        "## Limitations",
        "",
        "- Messages inside 2 days of closest approach are not used, so late geometry changes are invisible "
        "(see `failure_analysis.md`, e.g. `train:8732`).",
        "- `p_critical` is a ranking score from class-weighted training, not a calibrated probability.",
        "- Almost all Critical labels come from miss distance; only 3 validation encounters are Critical by Pc.",
        "- The sigma value 6.378136e7 is treated as a placeholder; this is an inference, not confirmed.",
        "- Validation only: there are no test outcomes, and no claim of operational reliability.",
        "",
    ]
    out = REPORTS_DIR / "model_card.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(REPORTS_DIR.parent.parent)} and ml/artifacts/demo_histories.csv ({len(histories)} messages)")


if __name__ == "__main__":
    main()
