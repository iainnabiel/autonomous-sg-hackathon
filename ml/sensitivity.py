"""SG-06.5 Evaluate quality sensitivity.

Run:    python -m ml.sensitivity      (after python -m ml.train --model upgrade --features base)
Writes: ml/reports/sensitivity.md

Uses the frozen model on the validation partition, primary cohort. Nothing is retrained.

1. By TCA band: performance grouped by how far the latest early message is from closest
   approach (real data, no perturbation).
2. Masked inputs: optional inputs removed from every validation message before features
   are built. These are SYNTHETIC perturbations to see how much the model leans on each
   input; they are not observed data-quality failures.

Telemetry sigma is an input like any other here; nothing in this report is a
model-confidence percentage.
"""

import warnings

import numpy as np
import pandas as pd
from sklearn.inspection import permutation_importance

from ml.config import REPORTS_DIR, SEED
from ml.data import load_labels, load_messages
from ml.evaluate import score
from ml.features import build_features
from ml.inference import load_model
from ml.split import load_split
from ml.train import apply_upgrade

TCA_BANDS = [2.0, 2.5, 3.0, 4.0, 7.5]


def _predict(model: dict, messages: pd.DataFrame) -> pd.DataFrame:
    f = build_features(messages)
    p = model["classifier"].predict_proba(f[model["feature_columns"]])[:, 1]
    tier, upgraded = apply_upgrade(f["persistence_tier"], p, model["threshold"])
    return pd.DataFrame({"persistence_tier": f["persistence_tier"], "predicted_tier": tier,
                         "p_critical": p, "latest_tca": f["time_to_tca"]}, index=f.index)


def _fmt(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def _row(name: str, y: pd.Series, d: pd.DataFrame, reference: pd.DataFrame | None = None) -> dict:
    m = score(y, d["predicted_tier"])
    r = score(y, d["persistence_tier"])
    c = m["per_tier"]["Critical"]
    has_critical = c["support"] > 0
    flagged = (d["predicted_tier"] == "Critical").any()
    row = {
        "condition": name,
        "encounters": m["n"],
        "Critical": c["support"],
        "rule Critical recall": _fmt(r["per_tier"]["Critical"]["recall"] if has_critical else None),
        "model Critical recall": _fmt(c["recall"] if has_critical else None),
        "model Critical precision": _fmt(c["precision"] if flagged else None),
        "model Critical F1": _fmt(m["critical_f1"] if has_critical else None),
        "false Critical": m["false_critical"],
    }
    if reference is not None:
        row["tiers changed"] = int((d["predicted_tier"] != reference["predicted_tier"]).sum())
    return row


def main() -> None:
    warnings.filterwarnings("ignore", message="y_pred contains classes not in y_true")
    model = load_model()
    split = load_split()
    labels = load_labels()
    val_ids = split.index[(split["partition"] == "validation") & ~split["final_is_early"]]
    messages = load_messages("train")
    messages = messages[messages["encounter_id"].isin(val_ids)]
    y = labels.loc[val_ids, "final_tier"]

    base = _predict(model, messages).loc[val_ids]

    bands = pd.cut(base["latest_tca"], TCA_BANDS, right=False)
    band_rows = [_row(f"{b.left:g}–{b.right:g} days", y[bands == b], base[bands == b]) for b in bands.cat.categories]

    latest_only = messages.sort_values("time_to_tca").loc[lambda m: m["time_to_tca"] >= 2].groupby("encounter_id").head(1)
    perturbations = {
        "No perturbation": messages,
        "Space weather masked (F10, AP)": messages.assign(F10=np.nan, AP=np.nan),
        "Sigmas masked (c_sigma_r, t_sigma_r)": messages.assign(c_sigma_r=np.nan, t_sigma_r=np.nan),
        "Object type unknown": messages.assign(c_object_type="UNSEEN"),
        "History removed (latest early message only)": latest_only,
    }
    mask_rows = [_row(name, y, _predict(model, msgs).loc[val_ids], base) for name, msgs in perturbations.items()]

    feats = build_features(messages).loc[val_ids]
    importance = permutation_importance(
        model["classifier"], feats[model["feature_columns"]], y.eq("Critical").astype(int),
        scoring="average_precision", n_repeats=5, random_state=SEED,
    )
    top = pd.DataFrame(
        {"mean drop in PR-AUC": importance.importances_mean, "std": importance.importances_std},
        index=pd.Index(model["feature_columns"], name="feature"),
    ).sort_values("mean drop in PR-AUC", ascending=False).head(8)

    def table(rows: list[dict]) -> str:
        return pd.DataFrame(rows).set_index("condition").to_markdown()

    lines = [
        "# Quality sensitivity (SG-06.5)",
        "",
        f"Generated by `python -m ml.sensitivity`. Frozen model `{model['model_version']}`, validation partition, "
        f"primary cohort ({len(val_ids):,} encounters). Nothing is retrained.",
        "",
        "## By time to closest approach of the latest early message",
        "",
        "Real data, grouped. Small Critical counts make per-band recall noisy.",
        "",
        table(band_rows),
        "",
        "## Masked inputs (synthetic perturbations)",
        "",
        "Each row removes an optional input from every validation message before features are built. "
        "These are synthetic stress tests, not observed failures; they show how much the model relies on each "
        "input. Sigma here is a telemetry input, not a confidence score.",
        "",
        table(mask_rows),
        "",
        "`tiers changed` counts validation encounters whose predicted tier differs from the unperturbed run; "
        "aggregate scores can stay the same when upgrades are both added and removed.",
        "",
        "## Which inputs the upgrade classifier relies on",
        "",
        "Permutation importance on validation: how much the classifier's PR-AUC for Critical drops when one "
        "feature is shuffled. Shows reliance, not physical causation.",
        "",
        top.to_markdown(floatfmt=".4f"),
        "",
        "Rule recall changes only when the rule's inputs (latest risk and miss distance) change, so it stays "
        "constant across these rows.",
        "",
    ]
    out = REPORTS_DIR / "sensitivity.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(REPORTS_DIR.parent.parent)}")


if __name__ == "__main__":
    main()
