"""SG-06.2 Investigate missed Critical cases.

Run:    python -m ml.failures          (after python -m ml.train for persistence and upgrade_base)
Writes: ml/reports/failure_analysis.md

Validation partition, primary cohort. Compares persistence with the shipped upgrade
model: Critical support, detected and missed cases, the probability-critical subset,
added false alarms, and selected missed examples with their full message history.
Examples are selected illustrations, not a sample of typical behaviour.
"""

import pandas as pd

from ml.config import ARTIFACTS_DIR, CRITICAL_DISTANCE_M, CRITICAL_LOG_PC, EARLY_CUTOFF_DAYS, REPORTS_DIR
from ml.data import load_labels, load_messages

N_EXAMPLES = 2


def _load(run: str) -> pd.DataFrame:
    path = ARTIFACTS_DIR / run / "validation_predictions.csv"
    if not path.exists():
        raise FileNotFoundError(f"{path} not found; run python -m ml.train for {run} first")
    return pd.read_csv(path).set_index("encounter_id")


def _counts(name: str, y: pd.Series, pred: pd.Series) -> dict:
    crit = y == "Critical"
    return {
        "model": name,
        "Critical support": int(crit.sum()),
        "detected": int((crit & (pred == "Critical")).sum()),
        "missed": int((crit & (pred != "Critical")).sum()),
        "missed as Safe": int((crit & (pred == "Safe")).sum()),
        "false Critical alarms": int((~crit & (pred == "Critical")).sum()),
    }


def _history(messages: pd.DataFrame, encounter_id: str) -> str:
    m = messages[messages["encounter_id"] == encounter_id].sort_values("time_to_tca", ascending=False)
    m = m.assign(input=m["time_to_tca"].ge(EARLY_CUTOFF_DAYS).map({True: "yes", False: "no (after cutoff)"}))
    cols = ["time_to_tca", "miss_distance", "risk", "c_sigma_r", "t_sigma_r", "input"]
    return m[cols].round(3).to_markdown(index=False)


def main() -> None:
    labels = load_labels()
    persistence = _load("persistence")
    model = _load("upgrade_base")
    v = model.join(labels[["final_risk_log10_pc", "final_miss_distance_m"]])
    v = v[~v["final_is_early"]]
    y = v["final_tier"]

    pc_critical = v["final_risk_log10_pc"] >= CRITICAL_LOG_PC
    summary = pd.DataFrame(
        [
            _counts("Persistence", y, persistence.loc[v.index, "predicted_tier"]),
            _counts("Upgrade (base), shipped", y, v["predicted_tier"]),
            _counts("Persistence, Pc-critical subset", y[pc_critical], persistence.loc[v.index[pc_critical], "predicted_tier"]),
            _counts("Upgrade, Pc-critical subset", y[pc_critical], v.loc[pc_critical, "predicted_tier"]),
        ]
    ).set_index("model")

    missed = v[(y == "Critical") & (v["predicted_tier"] != "Critical")].sort_values("p_critical")
    upgraded = v[v["upgraded"]]
    examples = missed[missed["persistence_tier"] == "Safe"].head(N_EXAMPLES)
    if len(examples) < N_EXAMPLES:
        examples = pd.concat([examples, missed.drop(examples.index).head(N_EXAMPLES - len(examples))])
    pc_missed = missed[missed["final_risk_log10_pc"] >= CRITICAL_LOG_PC]
    examples = pd.concat([examples, pc_missed.drop(examples.index, errors="ignore").head(1)])
    messages = load_messages("train")

    lines = [
        "# Failure analysis (SG-06.2)",
        "",
        "Generated by `python -m ml.failures`. Validation partition, primary cohort "
        f"({len(v):,} encounters; excludes encounters whose final message is itself ≥ 2 days out).",
        "",
        "## Detection summary",
        "",
        summary.to_markdown(),
        "",
        f"- Probability-critical (final risk ≥ {CRITICAL_LOG_PC:g}) encounters are rare: "
        f"{int(pc_critical.sum())} in this cohort. Any recall on that subset is anecdotal.",
        f"- The model made {len(upgraded)} upgrades: {int((upgraded['final_tier'] == 'Critical').sum())} correct, "
        f"{int((upgraded['final_tier'] != 'Critical').sum())} false alarms "
        f"({(upgraded['final_tier'] != 'Critical').mean():.0%} of upgrades).",
        "",
        "## Missed Critical encounters",
        "",
        f"{len(missed)} Critical encounters were not flagged. What they looked like 2+ days out:",
        "",
        missed["persistence_tier"].value_counts().rename("count").to_markdown(),
        "",
        f"- Final miss distance: median {missed['final_miss_distance_m'].median():.0f} m "
        f"(range {missed['final_miss_distance_m'].min():.0f}–{missed['final_miss_distance_m'].max():.0f} m). "
        f"All {int((missed['final_miss_distance_m'] < CRITICAL_DISTANCE_M).sum())} are Critical by distance.",
        f"- Model score: median p_critical {missed['p_critical'].median():.3f}, below the upgrade threshold, so "
        "nothing in the early messages separated them from the many Elevated encounters that stayed Elevated.",
        "",
        "## Selected examples (illustrations, not typical cases)",
        "",
    ]
    for eid, row in examples.iterrows():
        lines += [
            f"### {eid}",
            "",
            f"- Looked **{row['persistence_tier']}** at the latest early message; model score "
            f"p_critical = {row['p_critical']:.4f}, so not upgraded.",
            f"- Final: miss distance {row['final_miss_distance_m']:.0f} m, log10 Pc "
            f"{row['final_risk_log10_pc']:.2f} → **Critical**.",
            "",
            _history(messages, eid),
            "",
        ]
    lines += [
        "## Limitation",
        "",
        "The model only sees messages ≥ 2 days before closest approach. When an encounter's geometry "
        "changes sharply inside those 2 days (as in the examples above), the early messages carry no "
        "warning and neither the rule nor the model can flag it. The operator would learn of it only from "
        "later messages, so the dashboard must keep re-assessing as new messages arrive rather than "
        "treating a 2-day-out Safe as final.",
        "",
    ]
    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    out = REPORTS_DIR / "failure_analysis.md"
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out.relative_to(REPORTS_DIR.parent.parent)}")


if __name__ == "__main__":
    main()
